const dictionaries: Record<SupportedLanguage, Dictionary> = { es, en, fr, pt }

export function translate(language: SupportedLanguage, key: TranslationKey, params: TranslationParams = {}): string {
    // 1. Engañamos a TS localmente para que nos deje buscar en el objeto sin llorar
    const safeKey = key as keyof typeof es;
    // 2. Buscamos en el diccionario. Si no existe, usamos la llave dinámica tal cual.
    const template = dictionaries[language]?.[safeKey] || es[safeKey] || (key as string);
    return template.replace(/\{(\w+)\}/g, (_, token: string) => String(params[token] ?? `{${token}}`));
}

const apiMessageKeys: Record<string, TranslationKey> = {
    'API de cámara no disponible en este navegador.': 'error.cameraApi',
    'Cámara en uso. Cierre otras aplicaciones; reintentando…': 'error.cameraBusy',
    'Permiso de cámara denegado.': 'error.cameraPermission',
    'No se pudo abrir la cámara. Verifique permisos del navegador.': 'error.cameraOpen',
    'Indique Usuario, DNI o RUC.': 'error.identityRequired',
    'Indique la contraseña.': 'error.passwordRequired',
    'La camara no esta lista.': 'error.cameraNotReady',
    'La camara no esta lista para el registro facial.': 'error.cameraNotReady',
    'Mantenga el rostro visible y centrado en el ovalo.': 'error.faceCentered',
    'La contraseña debe tener al menos 6 caracteres.': 'error.passwordLength',
    'Las contraseñas no coinciden.': 'error.passwordMismatch',
}

export function translateApiMessage(language: SupportedLanguage, message: unknown): string {
    const raw = String(message || '').trim()
    const key = apiMessageKeys[raw]
    return key ? translate(language, key) : raw
}

interface I18nValue {
    language: SupportedLanguage
    countryIso2: string
    prefs: PlatformPrefs
    t: (key: TranslationKey, params?: TranslationParams) => string
    localizeMessage: (message: unknown) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
    const [prefs, setPrefs] = useState<PlatformPrefs>(() => getPlatformPrefs())
    const language = (['es', 'en', 'fr', 'pt'].includes(prefs.languageCode)
        ? prefs.languageCode
        : 'es') as SupportedLanguage

    useEffect(() => {
        applyHtmlLang(language, prefs.countryIso2)
        const onPrefs = () => setPrefs(getPlatformPrefs())
        window.addEventListener('mining-platform-prefs', onPrefs)
        return () => window.removeEventListener('mining-platform-prefs', onPrefs)
    }, [language, prefs.countryIso2])

    const t = useCallback(
        (key: TranslationKey, params?: TranslationParams) => translate(language, key, params),
        [language]
    )
    const localizeMessage = useCallback(
        (message: unknown) => translateApiMessage(language, message),
        [language]
    )
    const value = useMemo(
        () => ({ language, countryIso2: prefs.countryIso2, prefs, t, localizeMessage }),
        [language, prefs, t, localizeMessage]
    )
    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
    const context = useContext(I18nContext)
    if (!context) throw new Error('useI18n debe usarse dentro de I18nProvider')
    return context
}
