const dictionaries: Record<SupportedLanguage, Dictionary> = { es, en, fr, pt }

export function translate(language: SupportedLanguage, key: TranslationKey, params: TranslationParams = {}): string {
    const template = dictionaries[language]?.[key] || es[key] || key
    return template.replace(/\{(\w+)\}/g, (_, token: string) => String(params[token] ?? `{${token}}`))
}

