export type SupportedLanguage = 'es' | 'en' | 'fr' | 'pt'
export type TranslationParams = Record<string, string | number>

const countryLanguageOverrides: Record<string, SupportedLanguage> = {
    BR: 'pt',
    CA: 'fr',
    HT: 'fr',
    GF: 'fr',
    GP: 'fr',
    MQ: 'fr',
    US: 'en',
    BZ: 'en',
    GY: 'en',
    JM: 'en',
    TT: 'en',
    BB: 'en',
    BS: 'en',
}

export function languageForCountry(iso2: string | undefined, defaultLocale?: string): SupportedLanguage {
    const country = String(iso2 || 'PE').toUpperCase()
    if (countryLanguageOverrides[country]) return countryLanguageOverrides[country]
    const localeLanguage = String(defaultLocale || '').slice(0, 2).toLowerCase()
    if (localeLanguage === 'en' || localeLanguage === 'fr' || localeLanguage === 'pt') {
        return localeLanguage
    }
    return 'es'
}

